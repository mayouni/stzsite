STRIP_CSS = ("<style>/*stz-ladder*/.stz-ladder{border:1px solid var(--line);border-inline-start:4px solid var(--accent);background:var(--panel);"
             "padding:8px 14px;border-radius:8px;margin:4px 0 16px;color:var(--ink)}.stz-ladder b,.stz-ladder a{color:var(--accent)}"
             ".stz-ladder bdi{white-space:nowrap;font-family:ui-monospace,Consolas,monospace}</style>")

def inject_reader(text, run):
    """the rung of each chapter, under its title, in each of the four languages"""
    text = re.sub(r"<!--stz-ladder-->.*?<!--/stz-ladder-->", "", text, flags=re.S)
    text = re.sub(r"<style>/\*stz-ladder\*/.*?</style>", "", text, flags=re.S)       # by marker, so an edited style never stacks
    text = text.replace("</head>", STRIP_CSS + "</head>", 1)
    rungs = rung_of(run)
    def strip(lang, n):
        lv = rungs.get(n)
        if not lv: return ""
        p = run["projects"][lv["earned-by"]]
        b = p["brief"].get(lang) or p["brief"]["en"]
        upto = len(lv["chapters"])
        if lang in ("en", "fr"):
            t = T[lang]
            body = t["strip"].format(rung=esc(lv["id"].upper()), name=esc(NAMES[lv["named"]][0 if lang == "en" else 1]),
                                     n=upto, pid=esc(lv["earned-by"]), what=inline_code(b["what"]))
            link = f' <a href="{lang}/learn.html#ladder">{t["strip_link"]}</a>'
        else:
            # Arabic and Hausa: only the library's own words, the brief in that language
            body = f'{esc(lv["id"].upper())} · 1 – {upto} · <bdi>{esc(lv["earned-by"])}</bdi> · {inline_code(b["what"])}'
            link = ' <a href="en/learn.html#ladder">S0 – S4</a>'
        return f'<!--stz-ladder--><p class="stz-ladder"><b>{body.split(" · ", 1)[0]}</b> · {body.split(" · ", 1)[1]}{link}</p><!--/stz-ladder-->'
    out, pos = [], 0
    for m in re.finditer(r'<article id="(en|fr|ar|ha)-(\d+)"[^>]*>', text):
        lang, n = m.group(1), int(m.group(2))
        h = text.find("</h1>", m.end())
        if h < 0: continue
        out.append(text[pos:h + 5]); out.append(strip(lang, n)); pos = h + 5
    out.append(text[pos:])
    return "".join(out)
