        new = [ch[i] for i in range(prev + 1, n + 1) if i in ch]
        prev = n
        p = run["projects"][lv["earned-by"]]
        b = p["brief"].get(lang) or p["brief"]["en"]
        chap = " · ".join(f'<a href="../reader.html#{lang}:{c["n"]}">{c["n"]} {esc(c.get(lang, c["en"]))}</a>' for c in new)
