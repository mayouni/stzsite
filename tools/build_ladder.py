"""The learner's ladder: on the Learn page, and on every chapter of the reader.

The Learning System's five rungs, S0 Explorer to S4 Master, are declared by the
library (program/levels.zknw) and earned by a project that passes its guard,
never by a score. tools/ladder_run.py asked the library which chapters each
rung needs, had each project's guard prove itself on its wrong and right
samples, and asked where a new learner stands. This module turns that run into

  - the ladder on the Learn page (placeholder <!--LADDER-->): each rung, the
    chapters it adds, the project that earns it, what the guard checks, and the
    guard's own verdicts on its samples; then "where you stand", run;
  - a line on every chapter of the reader (reader.html): the rung the chapter
    belongs to and what earns it. The reader is generated by the library; the
    site adds this line to its copy between markers, so a rebuild replaces it
    rather than stacking it. The Arabic and Hausa lines use only the library's
    own text (the project's brief in that language), no translation by the site.

Pedagogy proposed it as "the ladder always visible"; decided
by the author on 2026-10-03.
"""
